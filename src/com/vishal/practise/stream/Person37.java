package com.vishal.practise.stream;

public class Person37 {

	 String name;
	
	 int age;

	/**
	 * @param name
	 * @param age
	 */
	public Person37(String name, int age) {
		super();
		this.name = name;
		this.age = age;
	}

	/**
	 * @return the name
	 */
	public String getName() {
		return name;
	}

	/**
	 * @param name the name to set
	 */
	public void setName(String name) {
		this.name = name;
	}

	/**
	 * @return the age
	 */
	public int getAge() {
		return age;
	}

	/**
	 * @param age the age to set
	 */
	public void setAge(int age) {
		this.age = age;
	}

	@Override
	public String toString() {
		return "Person37 [name=" + name + ", age=" + age + "]";
	}
	
	
}
