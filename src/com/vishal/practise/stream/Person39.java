package com.vishal.practise.stream;

public class Person39 {

	String city;
	int age;
	/**
	 * @param city
	 * @param age
	 */
	public Person39(String city, int age) {
		super();
		this.city = city;
		this.age = age;
	}
	/**
	 * @return the city
	 */
	public String getCity() {
		return city;
	}
	/**
	 * @param city the city to set
	 */
	public void setCity(String city) {
		this.city = city;
	}
	/**
	 * @return the age
	 */
	public int getAge() {
		return age;
	}
	/**
	 * @param age the age to set
	 */
	public void setAge(int age) {
		this.age = age;
	}
	@Override
	public String toString() {
		return "Person39 [city=" + city + ", age=" + age + "]";
	}
	
	
}
